-- Path to Polish V2 ONLY. Run manually with DIRECT TLS Neon connection after
-- reviewing the existing project's V1 tables. Never apply to public schema.
-- This script is idempotent for a FRESH schema; do not change live columns
-- without a reviewed/versioned follow-up migration.
CREATE SCHEMA IF NOT EXISTS ptp_v2;

CREATE TABLE IF NOT EXISTS ptp_v2.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL,
 salt TEXT NOT NULL,
 password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ptp_v2.sessions (
 token_hash TEXT PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES ptp_v2.users(id),
 expiry BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS ptp_v2.families (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 owner_id BIGINT NOT NULL REFERENCES ptp_v2.users(id)
);
CREATE TABLE IF NOT EXISTS ptp_v2.members (
 family_id BIGINT NOT NULL REFERENCES ptp_v2.families(id),
 user_id BIGINT NOT NULL REFERENCES ptp_v2.users(id),
 joined_at BIGINT NOT NULL,
 PRIMARY KEY(family_id,user_id)
);
CREATE TABLE IF NOT EXISTS ptp_v2.invitations (
 code_hash TEXT PRIMARY KEY,
 family_id BIGINT NOT NULL REFERENCES ptp_v2.families(id),
 expiry BIGINT NOT NULL,
 redeemed_by BIGINT REFERENCES ptp_v2.users(id)
);
CREATE TABLE IF NOT EXISTS ptp_v2.region_goals (
 family_id BIGINT NOT NULL REFERENCES ptp_v2.families(id),
 region TEXT NOT NULL,
 target BIGINT NOT NULL,
 PRIMARY KEY(family_id,region)
);
CREATE TABLE IF NOT EXISTS ptp_v2.activities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 family_id BIGINT NOT NULL REFERENCES ptp_v2.families(id),
 user_id BIGINT NOT NULL REFERENCES ptp_v2.users(id),
 item_id TEXT NOT NULL,
 mode TEXT NOT NULL,
 day TEXT NOT NULL,
 tier BIGINT NOT NULL,
 xp BIGINT NOT NULL,
 expedition_xp BIGINT NOT NULL,
 region TEXT NOT NULL,
 created_at BIGINT NOT NULL,
 UNIQUE(family_id,user_id,item_id,mode,day)
);
CREATE INDEX IF NOT EXISTS activities_week
 ON ptp_v2.activities(family_id,created_at,user_id);
CREATE TABLE IF NOT EXISTS ptp_v2.speech_usage (
 user_id BIGINT NOT NULL REFERENCES ptp_v2.users(id),
 day TEXT NOT NULL,
 requests BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(user_id,day)
);
CREATE TABLE IF NOT EXISTS ptp_v2.login_throttle (
 identity TEXT PRIMARY KEY,
 failures BIGINT NOT NULL,
 first_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS ptp_v2.password_reset_tokens (
 token_hash TEXT PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES ptp_v2.users(id),
 expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS password_reset_user
 ON ptp_v2.password_reset_tokens(user_id);
CREATE TABLE IF NOT EXISTS ptp_v2.email_verifications (
 user_id BIGINT PRIMARY KEY REFERENCES ptp_v2.users(id),
 verified_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS ptp_v2.verification_tokens (
 token_hash TEXT PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES ptp_v2.users(id),
 expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS verification_token_user
 ON ptp_v2.verification_tokens(user_id);
CREATE TABLE IF NOT EXISTS ptp_v2.verification_throttle (
 identity TEXT PRIMARY KEY,
 attempts BIGINT NOT NULL,
 first_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS ptp_v2.recovery_throttle (
 identity TEXT PRIMARY KEY,
 attempts BIGINT NOT NULL,
 first_at BIGINT NOT NULL
);

